import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
import pg from 'pg';

const directory = resolve(process.env.DATA_DIR || '.storage');
const connectionString = process.env.DATABASE_URL || process.env.POSTGRES_URL;
export const hosted = Boolean(connectionString) || process.env.VERCEL === '1';
const pool = connectionString ? new pg.Pool({connectionString,max:5,connectionTimeoutMillis:8000}) : null;
pool?.on('error',error=>console.error('PostgreSQL idle connection:',error.code || error.name));
const schema = `
  CREATE TABLE IF NOT EXISTS users(
    id INTEGER ${hosted ? 'GENERATED BY DEFAULT AS IDENTITY ' : ''}PRIMARY KEY, name TEXT NOT NULL, login TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('teacher','student')),
    class_code TEXT UNIQUE, teacher_id INTEGER REFERENCES users(id),
    grade INTEGER CHECK(grade IN (8,9))
  );
  CREATE TABLE IF NOT EXISTS sessions(
    token TEXT PRIMARY KEY, user_id INTEGER REFERENCES users(id), expires BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS attempts(
    id TEXT PRIMARY KEY, owner TEXT NOT NULL, user_id INTEGER REFERENCES users(id),
    grade INTEGER NOT NULL, mode TEXT NOT NULL, lesson TEXT NOT NULL, questions TEXT NOT NULL,
    expires BIGINT, result TEXT, date TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS attempts_user ON attempts(user_id,date);
  CREATE TABLE IF NOT EXISTS rooms(
    code TEXT PRIMARY KEY, teacher INTEGER NOT NULL REFERENCES users(id), team_mode INTEGER NOT NULL,
    state TEXT NOT NULL, idx INTEGER NOT NULL, questions TEXT NOT NULL, created BIGINT NOT NULL,
    grade INTEGER CHECK(grade IN (8,9))
  );
  CREATE TABLE IF NOT EXISTS players(
    code TEXT NOT NULL REFERENCES rooms(code), token TEXT NOT NULL, name TEXT NOT NULL, team TEXT NOT NULL,
    PRIMARY KEY(code,token), UNIQUE(code,name)
  );
  CREATE TABLE IF NOT EXISTS responses(
    code TEXT NOT NULL, token TEXT NOT NULL, idx INTEGER NOT NULL, correct INTEGER NOT NULL,
    PRIMARY KEY(code,token,idx), FOREIGN KEY(code,token) REFERENCES players(code,token)
  );
`;

function openSQLite() {
  mkdirSync(directory, { recursive: true });
  const database = new DatabaseSync(resolve(directory, 'atlas.sqlite'));
  database.exec('PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON; PRAGMA busy_timeout=5000;'+schema);
  for (const table of ['users','rooms']) {
    if (!database.prepare(`PRAGMA table_info(${table})`).all().some(column=>column.name === 'grade')) {
      database.exec(`ALTER TABLE ${table} ADD COLUMN grade INTEGER CHECK(grade IN (8,9))`);
    }
  }
  return database;
}
const db = hosted ? null : openSQLite();
let initialized;

async function initializePostgres() {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(650288031)');
    await client.query(schema);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK').catch(()=>{});
    throw error;
  } finally {
    client.release();
  }
}

async function query(sql, params) {
  if (!pool) throw Object.assign(new Error('Máy chủ chưa được cấu hình cơ sở dữ liệu.'),{status:503});
  initialized ??= initializePostgres().catch(error=>{
    initialized = undefined;
    throw error;
  });
  await initialized;
  let index = 0;
  return pool.query(sql.replace(/\?/g,()=>`$${++index}`),params);
}

export const one = async (sql, ...params) => db ? db.prepare(sql).get(...params) : (await query(sql,params)).rows[0];
export const all = async (sql, ...params) => db ? db.prepare(sql).all(...params) : (await query(sql,params)).rows;
export const run = async (sql, ...params) => db ? db.prepare(sql).run(...params).changes : (await query(sql,params)).rowCount;
export async function closeStorage() {
  if (db) db.close();
  else if (pool) await pool.end();
}

function localTeacherKey() {
  const path = resolve(directory, 'teacher-key.txt');
  try {
    writeFileSync(path, randomBytes(18).toString('base64url'), { flag: 'wx', mode: 0o600 });
  } catch (error) {
    if (error.code !== 'EEXIST') throw error;
  }
  return readFileSync(path, 'utf8').trim();
}
export const teacherKey = process.env.TEACHER_KEY || (db ? localTeacherKey() : null);
